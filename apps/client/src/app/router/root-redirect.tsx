
import { Navigate } from "react-router-dom"
import {useAuthBootstrap} from "@/hooks/use-auth-bootstrap.ts";

// Компонент для index route корня приложения.
// На "/" нет собственной страницы: это точка входа, которая выбирает
// правильный стартовый экран в зависимости от состояния авторизации.
export const RootRedirect = () => {
    // Дожидаемся bootstrap авторизации перед выбором направления,
    // чтобы пользователь с валидной сессией не увидел лишний переход на login.
    const user = useAuthBootstrap()

    // Авторизованного пользователя отправляем в основной список событий,
    // гостя - на страницу входа. replace сохраняет историю браузера чистой:
    // корневой "/" не остается промежуточной страницей для кнопки "назад".
    return <Navigate to={user ? '/events' : '/login'} replace/>
}
